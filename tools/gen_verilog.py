"""Generate design.v, the Verilog the platform builds, from the Amaranth source.

Usage: python tools/gen_verilog.py [OUT.v]   (default: design.v at the repo root)

Why this exists: Amaranth 0.5 emits a full zero initialiser for every Memory,
one Verilog assignment per word. For this solver that is about 2.6M lines,
and yosys needs tens of GB and hours to read it, so the platform build of
the Amaranth entry runs out of memory. This script converts design.Entry
(with solver.Solver using plain Amaranth Memories) to RTLIL, deletes the
$meminit cells, and writes Verilog. The memories are left without an
initialiser; synth_ecp5 maps them to DP16KD block RAM, which powers up
zeroed, and the solver clears every memory it relies on at START anyway.

The Amaranth files (design.py, solver.py) are the real source; design.v is a
generated artifact checked in so the platform can build it. Needs yosys on
PATH (for example from oss-cad-suite).
"""

import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from amaranth.back import rtlil  # noqa: E402

import solver  # noqa: E402
from design import Entry  # noqa: E402

TOP = "agentsat_entry"


def main():
    out = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "design.v"))
    solver.Solver.bram_primitives = False  # plain Memories; yosys infers DP16KD
    e = Entry()
    ports = [e.wb_cyc, e.wb_stb, e.wb_we, e.wb_adr, e.wb_dat_w, e.wb_sel, e.wb_dat_r, e.wb_ack]
    with tempfile.TemporaryDirectory() as tmp:
        il = os.path.join(tmp, "entry.il")
        with open(il, "w") as f:
            f.write(rtlil.convert(e, name=TOP, ports=ports))
        subprocess.run(
            ["yosys", "-q", "-p",
             f"read_rtlil {il}; delete t:$meminit_v2 t:$meminit; hierarchy -check -top {TOP}; "
             f"proc; opt_clean; write_verilog -noattr {out}"],
            check=True,
        )
    with open(out) as f:
        text = f.read()
    header = ("// GENERATED by tools/gen_verilog.py from design.py and solver.py (Amaranth).\n"
              "// Do not edit by hand; edit the Amaranth source and regenerate.\n")
    with open(out, "w") as f:
        f.write(header + text)
    print(f"wrote {out}: {len(text)} bytes, {text.count(chr(10))} lines, "
          f"{text.count('initial')} initial blocks")


if __name__ == "__main__":
    main()
